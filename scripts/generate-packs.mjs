// generate-packs.mjs — turns data/packs.js into real game pages.
// For every pack it writes game/<id>.html, assets/games/<id>/icon.svg and a data/games.json entry.
// Run: npm run packs   (safe to re-run; existing hand-made games are never touched)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const packs = require(join(root, 'data', 'packs.js'));
const gamesPath = join(root, 'data', 'games.json');
const games = JSON.parse(readFileSync(gamesPath, 'utf8'));

const GRADIENTS = {
  quiz: ['#c7d2fe', '#6366f1'], sort: ['#bbf7d0', '#16a34a'], sequence: ['#fde68a', '#d97706'],
  match: ['#f5d0fe', '#a21caf'], spell: ['#bae6fd', '#0284c7'], pop: ['#fecdd3', '#e11d48'],
};
const LABEL = { quiz: 'Quiz', sort: 'Sort it', sequence: 'Put in order', match: 'Memory pairs', spell: 'Spelling', pop: 'Bubble pop' };
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const page = p => `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width,initial-scale=1" />
  <title>${esc(p.title)} — Kiddoxy</title>
  <meta name="description" content="${esc(p.desc)}">
  <link rel="icon" href="/kiddoxy.png" type="image/png">
  <link rel="stylesheet" href="/styles/kid-kit.css">
  <link rel="stylesheet" href="/styles/pack.css">
  <script defer src="/scripts/game-brand.js"></script>
  <script defer src="/game-shell.js"></script>
  <script src="/scripts/kid-kit.js"></script>
</head>
<body>
<!-- Generated by scripts/generate-packs.mjs from data/packs.js — edit the pack there, not this file. -->
<div class="wrap">
  <header class="game-header">
    <h1>${p.icon} ${esc(p.title)}</h1>
    <div class="hud">
      <span class="pill">Round <span id="round">0/10</span></span>
      <span class="pill">⭐ <span id="score">0</span></span>
      <button class="btn secondary icon-btn" id="muteBtn" aria-label="Sound">🔊</button>
    </div>
  </header>
  <main class="game-main">
    <div class="panel" id="game" aria-live="polite"></div>
  </main>
  <div class="ad-banner">AD_BANNER_PLACEHOLDER</div>
</div>
<script>window.PACK_ID = ${JSON.stringify(p.id)};</script>
<script src="/data/packs.js"></script>
<script src="/scripts/pack-engine.js"></script>
</body>
</html>
`;

const icon = p => {
  const [a, b] = GRADIENTS[p.type];
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="${b}"/></linearGradient></defs><rect width="128" height="128" rx="28" fill="url(#g)"/><text x="64" y="70" font-size="70" text-anchor="middle" dominant-baseline="middle">${p.icon}</text></svg>`;
};

const handMade = new Set(games.filter(g => !g.pack).map(g => g.id));
let written = 0;
for (const p of packs) {
  if (handMade.has(p.id)) { console.warn(`! skipped ${p.id}: a hand-made game already uses this id`); continue; }
  if (!GRADIENTS[p.type]) throw new Error(`Unknown type ${p.type} in ${p.id}`);
  writeFileSync(join(root, 'game', `${p.id}.html`), page(p));
  mkdirSync(join(root, 'assets', 'games', p.id), { recursive: true });
  writeFileSync(join(root, 'assets', 'games', p.id, 'icon.svg'), icon(p));
  const entry = {
    id: p.id, title: p.title, shortDesc: p.desc, interaction: 'tap', orientation: 'portrait', complexity: 'simple',
    route: `game/${p.id}.html`, category: p.cat, pack: true, kind: LABEL[p.type],
    adPolicy: { banner: true }, assets: [`assets/games/${p.id}/icon.svg`], reward: 'stars', priority: 5,
  };
  const i = games.findIndex(g => g.id === p.id);
  if (i >= 0) games[i] = entry; else games.push(entry);
  written++;
}
// drop entries for packs that were removed from packs.js
const live = new Set(packs.map(p => p.id));
const out = games.filter(g => !g.pack || live.has(g.id));
writeFileSync(gamesPath, JSON.stringify(out, null, 2) + '\n');
console.log(`Generated ${written} pack games. games.json now lists ${out.length} games.`);
